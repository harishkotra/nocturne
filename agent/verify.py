def gate_selftest() -> tuple[list[str], list[str]]:
    """Run illegal and legal proposals straight through the gates -- no model, no network.

    This is the part of acceptance criterion 1 that must not depend on how cooperative the model
    happens to be: the guards have to refuse bad mutations on their own.
    """
    policy = cons.Policy()
    ok: list[str] = []
    bad: list[str] = []
    for pass_name, proposals, expectation in GATE_CASES:
        state = cons.WorkingState(_fixture_items())
        accepted, rejected = cons._verify(pass_name, proposals, state, policy)
        want_accept = expectation == "__ACCEPT__"
        got = accepted if want_accept else rejected
        if not got:
            bad.append(
                f"{pass_name}: proposal was {'accepted' if not want_accept else 'refused'} when it must be "
                f"{'accepted' if want_accept else 'refused'}: {json.dumps(proposals[0])[:100]}"
            )
            continue
        entry = got[0]
        if want_accept:
            if not (entry.get("reason") or "").strip():
                bad.append(f"{pass_name}: accepted without a traceable reason")
            else:
                ok.append(f"{pass_name}: legal proposal accepted ({entry['reason'][:40]})")
            continue
        why = entry.get("rejectionReason") or ""
        if expectation not in why:
            bad.append(f"{pass_name}: refused for the wrong reason: {why[:90]!r} (wanted {expectation!r})")
        else:
            ok.append(f"{pass_name}: refused as required -- {why[:70]}")

    # the capacity rule is the cap, not a suggestion
    state = cons.WorkingState(_fixture_items())
    tight = cons.Policy(max_active_facts=2, stale_after_days=45)
    enforced = cons._enforce_capacity(state, tight)
    unprotected = [i for i in _fixture_items() if i["category"] not in tight.protected_categories]
    if len(enforced) != len(unprotected):
        bad.append(f"capacity enforcement dropped {len(enforced)} facts, expected {len(unprotected)} (cap 2)")
    else:
        ok.append(f"capacity enforcement dropped exactly the {len(unprotected)} unprotected facts")
    if len(state.active()) != 2:
        bad.append(f"capacity left {len(state.active())} active facts, cap is 2")
    if not all(policy.is_protected(i) for i in state.active()):
        bad.append("capacity enforcement left an unprotected fact or forgot a protected one")

    # durable categories belong in a long-term block, even if the model never promoted them
    state = cons.WorkingState(_fixture_items())
    promoted = cons._enforce_promotions(state, policy)
    if len(promoted) != 1 or promoted[0]["itemId"] != "m_6":
        bad.append(f"promotion enforcement produced {json.dumps([p['itemId'] for p in promoted])}, expected ['m_6']")
    else:
        ok.append(f"promotion enforcement moved m_6 scratch -> {promoted[0]['refs']['toBlock']}")
    if state.items["m_6"]["block"] != "human" or state.items["m_4"]["block"] != "human":
        bad.append("promotion enforcement put a durable fact in the wrong block")
    if state.items["m_1"]["block"] != "scratch":
        bad.append("promotion enforcement moved a context fact it had no rule for")
    return ok, bad


# --------------------------------------------------------------------- global guardrail
def audit_no_invention(
    store: MemoryStore, transcript: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Re-check every surviving active fact against the raw transcript, from scratch."""
    sources = [m["content"] for m in transcript]
    names = {n for s in sources for n in tm.proper_nouns(s)} | {"User", "The", "Assistant", "Nocturne"}
    clean, invented = [], []
    for item in store.active_items():
        cov, missing = tm.coverage(item["text"], sources)
        new_names = tm.proper_nouns(item["text"]) - names
        if cov < 1.0 or new_names:
            invented.append(
                {"itemId": item["itemId"], "text": item["text"], "coverage": round(cov, 3), "missing": missing, "newNames": sorted(new_names)}
            )
        else:
            clean.append(item)
    return clean, invented


def audit_mutations(store: MemoryStore, policy: cons.Policy) -> tuple[list[str], list[str]]:
    """Independently re-verify each recorded mutation against the store's own history."""
    good: list[str] = []
    bad: list[str] = []
    all_items = {i["itemId"]: i for i in store.all_items()}
    for m in store.mutations():
        if not m["accepted"]:
            if not (m.get("rejectionReason") or "").strip():
                bad.append(f"rejected {m['pass']}/{m['kind']} on {m['itemId']} has no rejection reason")
            else:
                good.append(f"rejection logged: {m['pass']}/{m['kind']} {m['itemId']}")
            continue
        reason = (m.get("reason") or "").strip()
        if not reason:
            bad.append(f"accepted {m['pass']}/{m['kind']} on {m['itemId']} has no reason")
            continue
        item = all_items.get(m["itemId"])
        if item is None:
            bad.append(f"accepted {m['pass']}/{m['kind']} references unknown item {m['itemId']}")
            continue
        refs = m["refs"] or {}
        if m["kind"] == "drop":
            other = all_items.get(refs.get("duplicateOf") or "")
            if not other:
                bad.append(f"drop of {m['itemId']} names no surviving duplicateOf")
                continue
            if tm.similarity(item["text"], other["text"]) < policy.similarity_threshold:
                bad.append(f"drop of {m['itemId']} would have scored below the {policy.similarity_threshold} threshold")
                continue
        if m["kind"] == "merge":
            sources = [all_items[f]["text"] for f in refs.get("fromIds", []) if f in all_items]
            merged = refs.get("mergedText") or ""
            cov, missing = tm.coverage(merged, sources + [item["text"]])
            if cov < 1.0:
                bad.append(f"accepted merge on {m['itemId']} is not traceable: {missing}")
                continue
            introduced = tm.proper_nouns(merged) - {n for s in sources + [item["text"]] for n in tm.proper_nouns(s)}
            if introduced:
                bad.append(f"accepted merge on {m['itemId']} introduced names {sorted(introduced)}")
                continue
        if m["kind"] == "promote" and refs.get("toBlock") not in cons.TARGET_BLOCKS:
            bad.append(f"accepted promote of {m['itemId']} targets illegal block {refs.get('toBlock')!r}")
            continue
        if m["kind"] == "forget":
            if policy.is_protected(item):
                bad.append(f"accepted forget of protected {m['itemId']} ({item['category']})")
                continue
            qualifies_capacity = m.get("policy") == "capacity"
            if not qualifies_capacity and item["ageDays"] <= policy.stale_after_days:
                bad.append(f"accepted forget of {m['itemId']} is neither stale nor over capacity")
                continue
        good.append(f"accepted mutation verified: {m['pass']}/{m['kind']} {m['itemId']}")
    return good, bad


# --------------------------------------------------------------------- main
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Nocturne verification")
    parser.add_argument("--provider", default=None, help="override base URL")
    parser.add_argument("--model", default=None)
    parser.add_argument("--keep", action="store_true", help="keep the verification databases")
    parser.add_argument("--quiet-model", action="store_true", help="use canned acknowledgements instead of generating assistant replies")
    args = parser.parse_args(argv)

    os.makedirs(DATA, exist_ok=True)
    load_dotenv(os.path.join(ROOT, ".env"))
    master = os.path.join(DATA, "verify_master.db")
    run_a = os.path.join(DATA, "verify_run.db")

    cfg = inf.config_from_env()
    if args.provider:
        cfg.base_url = args.provider
    if args.model:
        cfg.model = args.model
    policy = cons.Policy(
        max_active_facts=int(os.environ.get("MAX_ACTIVE_FACTS", 120)),
        stale_after_days=float(os.environ.get("STALE_AFTER_DAYS", 45)),
        protected_categories=tuple(
            c.strip() for c in os.environ.get("PROTECTED_CATEGORIES", "identity,preferences,commitments").split(",") if c.strip()
        ),
    )

    checks: list[Check] = []
    report(f"Nocturne verification  provider={cfg.base_url}  model={cfg.model}")
    report(f"policy: MAX_ACTIVE_FACTS={policy.max_active_facts} STALE_AFTER_DAYS={policy.stale_after_days:g} "
           f"PROTECTED={','.join(policy.protected_categories)}")

    report("\n0. guardrail self-test: illegal proposals straight into the gates (no model, no network)")
    gate_ok, gate_bad = gate_selftest()
    for line in gate_ok:
        report(f"   ok   {line}")
    for line in gate_bad:
        report(f"   BAD  {line}")
    checks.append(Check("the code gates refuse illegal mutations on their own", not gate_bad,
                        f"{len(gate_ok)} legal/refusal behaviours confirmed, {len(gate_bad)} failures"))

    probe = inf.test_connection(cfg)
    if not probe["ok"]:
        report(f"FATAL: provider unavailable: {probe.get('error')}")
        for step in probe["steps"]:
            report(f"   {step['url']} -> {step['status']} {str(step['body'])[:200]}")
        return 2
    report(f"provider probe: HTTP ok, model answered {probe.get('completion')!r}\n")

    # ---- 1. seed
    report("1. seeding the scripted 8-turn conversation through the real chat + encoder path")
    t0 = time.time()
    seeded = seed_store(master, cfg, policy, model_reply=not args.quiet_model)
    store: MemoryStore = seeded["store"]
    report(f"   seeded in {time.time()-t0:.1f}s; encoder proposed {seeded['extraction']['proposed']} facts, "
           f"accepted {len(seeded['extraction']['accepted'])}, rejected {len(seeded['extraction']['rejected'])}, "
           f"backdated {len(seeded['stale'])} episodic fact(s)")
    actions = top_up_duplicates(store, 2, 3)
    for a in actions:
        report(f"   fixture top-up: {a}")
    store.snapshot("fixture:seed-complete")
    pre_items = store.active_items()
    dup = measure_duplicates(pre_items, policy.similarity_threshold)
    protected = [i for i in pre_items if policy.is_protected(i)]
    stale = [i for i in pre_items if i["ageDays"] > policy.stale_after_days]
    durable = [i for i in pre_items if i["category"] in {"identity", "preferences", "commitments", "technical", "project"}]
    transcript = store.messages()
    seed_id = store.latest_snapshot()["snapshotId"]
    report(f"   active facts={len(pre_items)}  exact-dup pairs={len(dup['exact'])}  near-dup pairs={len(dup['near'])}  "
           f"stale={len(stale)}  protected={len(protected)}  durable={len(durable)}")

    checks.append(Check("fixture contains 2 exact duplicates", len(dup["exact"]) >= 2,
                        f"measured {len(dup['exact'])} pair(s): " + json.dumps(dup["exact"][:3])))
    checks.append(Check("fixture contains 3 near-duplicates", len(dup["near"]) >= 3,
                        f"measured {len(dup['near'])} restatement pair(s) (same content, different wording) "
                        f"that the engine flags at >=0.9: " + json.dumps(dup["near"][:3])))
    report(f"   {len(dup['belowThreshold'])} pair(s) sit below the 0.9 gate (0.7-0.9): "
           f"{json.dumps(dup['belowThreshold'][:3])} — the Dedupe gate must refuse these and say why")
    checks.append(Check("fixture contains 2 stale items", len(stale) >= 2,
                        f"measured {len(stale)} item(s) older than {policy.stale_after_days:g}d"))
    checks.append(Check("fixture contains a protected commitment", any(i["category"] == "commitments" for i in protected),
                        f"protected categories present: {sorted({i['category'] for i in protected})}"))
    checks.append(Check("fixture contains 4 durable facts", len(durable) >= 4,
                        f"measured {len(durable)} durable-category fact(s)"))

    store.close()
    clone_db(master, run_a)
    store = MemoryStore(run_a)

    # ---- 2. dry run must not touch state
    report("\n2. dry run: plan without applying")
    before = [i["itemId"] for i in store.active_items()]
    dry = cons.run_consolidation(store, cfg, policy, dry_run=True)
    after_dry = [i["itemId"] for i in store.active_items()]
    dry_props = sum(p["proposed"] for p in dry["passes"])
    dry_acc = sum(p["accepted"] for p in dry["passes"])
    report(f"   dry-run plan: proposed={dry_props} accepted(if applied)={dry_acc} "
           f"rejected={sum(p['rejected'] for p in dry['passes'])} active stays {len(before)}->{len(after_dry)}")
    checks.append(Check("dry run changes nothing", before == after_dry,
                        f"{len(before)} facts before, {len(after_dry)} after; snapshot labels="
                        + json.dumps([s["label"] for s in store.snapshots()][-3:])))
    checks.append(Check("dry run produces a non-trivial plan", dry_props > 0 and dry_acc > 0,
                        f"proposed {dry_props}, would accept {dry_acc}"))

    # ---- 3. real consolidation
    report("\n3. real consolidation run (dedupe -> merge -> promote -> forget)")
    result = cons.run_consolidation(store, cfg, policy, dry_run=False)
    for p in result["passes"]:
        report(f"   pass {p['pass']:7s} in={p['inputCount']:3d} proposed={p['proposed']:2d} accepted={p['accepted']:2d} "
               f"rejected={p['rejected']:2d} enforced={p['enforced']:2d} activeAfter={p['activeCountAfter']:3d} "
               f"snapshots={p['beforeSnapshot']}..{p['afterSnapshot']}" + (f" ERROR={p['error']}" if p["error"] else ""))
        for m in p["acceptedMutations"][:6]:
            report(f"      + {m['kind']:6s} {m['itemId']:6s} {str(m.get('reason'))[:78]}")
        for m in p["rejectedMutations"][:6]:
            report(f"      - {m['kind']:6s} {str(m.get('itemId')):6s} {str(m.get('rejectionReason'))[:92]}")
    report(f"   totals: {result['totals']}")

    post = {i["itemId"]: i for i in store.active_items()}
    still_duplicated = [
        p for p in dup["pairs"] if p["loser"] in post and p["keeper"] in post
    ]
    stale_left = [i["itemId"] for i in stale if i["itemId"] in post]
    protected_left = [i for i in protected if i["itemId"] in post]
    committed = next((i for i in protected_left if i["category"] == "commitments"), None)
    promoted_items = [i for i in post.values() if i["block"] != "scratch"]

    checks.append(Check("duplicate pairs collapsed to one survivor", not still_duplicated,
                        f"{len(dup['pairs'])} duplicate pair(s) measured pre-run; {len(still_duplicated)} still "
                        f"present post-run {json.dumps(still_duplicated[:3])}"))
    checks.append(Check("stale items forgotten", not stale_left,
                        f"{len(stale)} stale fact(s) pre-run; still active post-run: {stale_left or 'none'}"))
    checks.append(Check("protected item kept", committed is not None,
                        f"commitment kept: {json.dumps(committed and committed['text'][:90])}; "
                        f"protected active {len(protected_left)}/{len(protected)}"))
    checks.append(Check("durable facts promoted", len(promoted_items) >= 4,
                        f"{len(promoted_items)} facts now live in persona/human/episodes"))

    # ---- 4. audit recorded mutations independently
    report("\n4. auditing every recorded mutation against the store's own history")
    good_audit, bad_audit = audit_mutations(store, policy)
    accepted_count = len([m for m in store.mutations() if m["accepted"]])
    rejected_count = len([m for m in store.mutations() if not m["accepted"]])
    report(f"   {accepted_count} accepted, {rejected_count} rejected; {len(good_audit)} re-verified, {len(bad_audit)} problems")
    for b in bad_audit[:8]:
        report(f"      ! {b}")
    checks.append(Check("every accepted mutation has a traceable reason", not bad_audit,
                        f"re-verified {len(good_audit)} mutation(s); problems: {bad_audit[:5] or 'none'}"))
    rejections = store.mutations(accepted=False)
    checks.append(Check("every rejected mutation is logged with a reason", all((r.get('rejectionReason') or '').strip() for r in rejections),
                        f"{len(rejections)} rejection(s) recorded across passes "
                        f"{sorted({r['pass'] for r in rejections}) or 'none'}"))

    # ---- 5. global no-invention guardrail
    report("\n5. guardrail: no surviving fact may invent anything")
    clean_facts, invented = audit_no_invention(store, transcript)
    report(f"   {len(clean_facts)}/{len(clean_facts)+len(invented)} active facts fully traceable to the transcript")
    for i in invented[:8]:
        report(f"      ! {i['itemId']} coverage={i['coverage']} missing={i['missing']} newNames={i['newNames']}")
    checks.append(Check("consolidation invented nothing", not invented,
                        f"untraceable facts: {json.dumps(invented[:3], ensure_ascii=False)}"))

    # ---- 6. recall quiz
    report("\n6. wake: self-quizzing against the consolidated store")
    quiz = run_quiz(store, cfg, policy, count=5, report_path=os.path.join(ROOT, "recall-report.json"))
    for q in quiz["questions"]:
        report(f"   [{'OK' if q['correct'] else 'NO'}] {q['question'][:62]!r}\n"
               f"        expected(store): {q['expectedAnswer'][:80]!r}\n"
               f"        model: {q['modelAnswer'][:80]!r}  coverage={q['coverage']} missing={q['missingTokens'][:6]}")
    fq = quiz["forgottenQuestion"]
    if fq:
        report(f"   forgotten probe [{ 'OK' if fq['passed'] else 'NO'}]: {fq['modelAnswer'][:90]!r}\n"
               f"        absentFromStore={fq['absentFromStore']} saidAbsent={fq['saidAbsent']} leaked={fq['leakedForgottenContent']}")
    else:
        report("   ! no forgotten item available to probe")
    report(f"   recall report written to {quiz['reportPath']}")
    checks.append(Check("5/5 survivors answered from the store",
                        quiz["survivorsCorrect"] >= 5 and quiz["survivorsTotal"] >= 5,
                        f"{quiz['survivorsCorrect']}/{quiz['survivorsTotal']} correct; report at {quiz['reportPath']}"))
    checks.append(Check("forgotten fact genuinely absent and reported as unknown", bool(fq and fq["passed"]),
                        json.dumps({k: fq.get(k) for k in ('itemId','absentFromStore','saidAbsent','leakedForgottenContent','storeMatches')} if fq else {"error": "no forgotten item"})))

    # ---- 7. retention policy changes the outcome
    report("\n7. retention policy: identical facts, two different MAX_ACTIVE_FACTS")
    baseline_forget = len(store.mutations(pass_name="forget", accepted=True))
    protected_pre = sum(1 for i in MemoryStore(master).active_items() if policy.is_protected(i))
    wide_db = os.path.join(DATA, "verify_wide.db")
    tight_db = os.path.join(DATA, "verify_tight.db")
    clone_db(master, wide_db)
    clone_db(master, tight_db)
    store.close()
    wide_store, tight_store = MemoryStore(wide_db), MemoryStore(tight_db)
    tight = cons.Policy(
        max_active_facts=6,
        stale_after_days=policy.stale_after_days,
        protected_categories=policy.protected_categories,
    )
    wide_res = cons.run_consolidation(wide_store, cfg, policy, passes=("forget",))
    tight_res = cons.run_consolidation(tight_store, cfg, tight, passes=("forget",))
    wide_forget = sum(p["accepted"] for p in wide_res["passes"])
    tight_forget = sum(p["accepted"] for p in tight_res["passes"])
    wide_active, tight_active = len(wide_store.active_items()), len(tight_store.active_items())
    floor = max(tight.max_active_facts, protected_pre)
    report(f"   MAX_ACTIVE_FACTS={policy.max_active_facts}: forgotten={wide_forget}, active left={wide_active}")
    report(f"   MAX_ACTIVE_FACTS=6:                forgotten={tight_forget}, active left={tight_active} "
           f"(floor {floor} = {protected_pre} protected facts that policy refuses to forget)")
    report(f"   full four-pass run on the same seed forgot {baseline_forget} in the Forget pass")
    checks.append(
        Check(
            "changing MAX_ACTIVE_FACTS changes the outcome",
            tight_forget > wide_forget and tight_active < wide_active and tight_active <= floor,
            f"wide: forget={wide_forget} left={wide_active}; tight: forget={tight_forget} left={tight_active}; "
            f"floor={floor}; full-run forget={baseline_forget}",
        )
    )

    # ---- summary
    report("\n" + "=" * 88)
    failed = [c for c in checks if not c.passed]
    for c in checks:
        report(f"[{'PASS' if c.passed else 'FAIL'}] {c.name}")
    report("=" * 88)
    report(f"{len(checks) - len(failed)}/{len(checks)} checks passed" + (f" -- {len(failed)} FAILED" if failed else " -- ALL PASS"))
    if not args.keep:
        for path in (run_a, wide_db, tight_db):
            for suffix in ("", "-wal", "-shm"):
                if os.path.exists(path + suffix):
                    os.remove(path + suffix)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
