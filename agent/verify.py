REPORTED: list[str] = []


@dataclass
class Check:
    name: str
    passed: bool
    detail: str


def report(line: str) -> None:
    REPORTED.append(line)
    print(line, flush=True)


# --------------------------------------------------------------------- fixtures
def clone_db(src: str, dst: str) -> None:
    if os.path.exists(dst):
        os.remove(dst)
    with sqlite3.connect(src) as s, sqlite3.connect(dst) as d:
        s.backup(d)


def seed_store(path: str, cfg: inf.ProviderConfig, policy: cons.Policy, model_reply: bool = True) -> dict[str, Any]:
    """Drive the scripted conversation through the real chat + encoder path."""
    if os.path.exists(path):
        for suffix in ("", "-wal", "-shm"):
            if os.path.exists(path + suffix):
                os.remove(path + suffix)
    store = MemoryStore(path)
    store.reset()
    system = (
        "You are Nocturne, a chat agent that consolidates its own memory while it sleeps. "
        "Acknowledge each fact briefly in one short sentence. Do not add new facts."
    )
    for i, user_text in enumerate(USER_TURNS):
        store.add_message("user", user_text)
        history = store.messages()[:-1]
        reply = ""
        if model_reply:
            try:
                reply = inf.chat(
                    cfg,
                    [{"role": "system", "content": system}]
                    + [{"role": m["role"], "content": m["content"]} for m in history]
                    + [{"role": "user", "content": user_text + "\n\nReply in at most 12 words."}],
                    want_json=False,
                ).strip()
            except inf.InferenceError as exc:
                reply = ""
                report(f"  ! assistant reply failed on turn {i+1}: {exc}")
        if not reply:
            reply = NOISE_REPLIES[i % len(NOISE_REPLIES)]
        store.add_message("assistant", reply)

    extraction = cons.extract_and_append(store, cfg)
    for rej in extraction["rejected"]:
        report(f"    encoder rejected: {rej['rejectionReason'][:110]} <- {json.dumps(rej['proposal'], ensure_ascii=False)[:90]}")

    # Backdate the episodic facts so the stale rule can be exercised without waiting 45 days.
    now = time.time()
    stale = []
    for item in store.active_items():
        low = item["text"].lower()
        if any(marker in low for marker in STALE_MARKERS):
            stale.append(store.set_created_at(item["itemId"], now - (policy.stale_after_days + 20) * 86400))
    return {"store": store, "extraction": extraction, "stale": [s for s in stale if s]}


def measure_duplicates(items: list[dict[str, Any]], threshold: float) -> dict[str, Any]:
    """Split flagged duplicates into verbatim repeats (exact) and restatements (near).

    The engine's own gate is token-set containment >= threshold; a restatement that omits a word
    is a strict subset and scores 1.0, so `near` is defined as "flagged, but different wording"
    rather than by a similarity band the containment measure cannot express.
    """
    pairs = []
    ordered = sorted(items, key=lambda i: (i["createdAt"], i["itemId"]))
    for i, a in enumerate(ordered):
        for b in ordered[i + 1 :]:
            score = tm.similarity(a["text"], b["text"])
            if score >= threshold:
                pairs.append(
                    {
                        "loser": b["itemId"],
                        "keeper": a["itemId"],
                        "similarity": round(score, 3),
                        "verbatim": tm.normalize(a["text"]) == tm.normalize(b["text"]),
                    }
                )
    exact = [p for p in pairs if p["verbatim"]]
    near = [p for p in pairs if not p["verbatim"]]
    below = []
    for i, a in enumerate(ordered):
        for b in ordered[i + 1 :]:
            score = tm.similarity(a["text"], b["text"])
            if 0.7 <= score < threshold:
                below.append({"a": a["itemId"], "b": b["itemId"], "similarity": round(score, 3)})
    return {"pairs": pairs, "exact": exact, "near": near, "belowThreshold": below}


def top_up_duplicates(store: MemoryStore, minimum_exact: int = 2, minimum_near: int = 3) -> list[str]:
    """Guarantee the fixture shape the spec requires, using text the encoder already produced.

    Extra copies are either verbatim (exact) or a restatement with one content word dropped (near).
    Every action is reported, so this can never quietly fabricate a passing demo.
    """
    actions: list[str] = []

    def counts() -> dict[str, Any]:
        return measure_duplicates(store.active_items(), 0.9)

    items = store.active_items()
    if not items:
        return ["fixture top-up skipped: the encoder produced no facts"]

    guard = 0
    while len(counts()["exact"]) < minimum_exact and guard < 8:
        donor = items[guard % len(items)]
        guard += 1
        store.append(donor["block"], {"text": donor["text"], "category": donor["category"]})
        actions.append(f"appended verbatim duplicate of {donor['itemId']} ({donor['text'][:58]!r})")

    long_enough = [i for i in items if len(tm.tokens(i["text"])) >= 6]
    guard = 0
    while len(counts()["near"]) < minimum_near and long_enough and guard < 12:
        donor = long_enough[guard % len(long_enough)]
        guard += 1
        restated = restate(donor["text"])
        if not restated:
            continue
        store.append(donor["block"], {"text": restated, "category": donor["category"]})
        actions.append(f"appended restatement of {donor['itemId']} -> {restated!r}")
    return actions


def restate(text: str) -> str | None:
    """Drop one content word: a restatement that says the same thing in different words.

    Strictly a subset, so the engine's containment measure still flags it as a duplicate -- which
    is what a real near-duplicate in agent memory looks like.
    """
    words = text.split()
    positions = [
        i
        for i, w in enumerate(words)
        if len(tm.stem_token(w.lower().strip(".,;:!?\"()"))) >= 4
        and tm.stem_token(w.lower().strip(".,;:!?\"()")) not in tm.STOPWORDS
    ]
    if not positions:
        return None
    cut = positions[len(positions) // 2]
    candidate = " ".join(words[:cut] + words[cut + 1 :])
    candidate = re.sub(r"\s+([,.;:!?])", r"\1", candidate)
    candidate = re.sub(r"\s+", " ", candidate).strip()
    if not candidate or tm.normalize(candidate) == tm.normalize(text):
        return None
    if tm.similarity(text, candidate) < 0.9:
        return None
    return candidate


